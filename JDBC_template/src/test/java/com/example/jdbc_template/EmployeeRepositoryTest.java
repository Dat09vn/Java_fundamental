package com.example.jdbc_template;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertNotNull;

import java.util.List;

import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.test.context.TestPropertySource;

import com.example.jdbc_template.Employee;
import com.example.jdbc_template.EmployeeRepository;

@SpringBootTest
@TestPropertySource(properties = {
        "spring.datasource.url=jdbc:h2:mem:testdb;MODE=Oracle;DB_CLOSE_DELAY=-1;DB_CLOSE_ON_EXIT=FALSE",
        "spring.datasource.driver-class-name=org.h2.Driver",
        "spring.datasource.username=sa",
        "spring.datasource.password=",
        "spring.sql.init.mode=never"
})
class EmployeeRepositoryTest {

    @Autowired
    private EmployeeRepository employeeRepository;

    @Autowired
    private JdbcTemplate jdbcTemplate;

    @Test
    void testCrudWithJdbcTemplate() {
        jdbcTemplate.update("DROP TABLE IF EXISTS employees");
        jdbcTemplate.update("CREATE TABLE employees (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name VARCHAR(255), email VARCHAR(255))");

        Long id = employeeRepository.save(new Employee(null, "Alice", "alice@example.com"));
        assertNotNull(id);

        Employee employee = employeeRepository.findById(id);
        assertEquals("Alice", employee.getName());
        assertEquals("alice@example.com", employee.getEmail());

        int updated = employeeRepository.updateEmail(id, "alice.new@example.com");
        assertEquals(1, updated);

        List<Employee> list = employeeRepository.findAll();
        assertEquals(1, list.size());

        int deleted = employeeRepository.deleteById(id);
        assertEquals(1, deleted);
    }
}
